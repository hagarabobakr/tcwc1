package com.hager.joke.service

import java.util.UUID

object JokePromptBuilder {
    fun build(word: String): String {
        val nonce = UUID.randomUUID()
        return """
           أنت واحد مصري خفيف الدم بتحكي نكت لأصحابك على القهوة.

        اكتب نكتة مصرية قصيرة جدًا مبنية على كلمة:
        "$word"

        شروط مهمة:
        - النكتة باللهجة المصرية العامية فقط.
        - تكون مضحكة فعلًا ومبنية على موقف يومي مصري.
        - لازم يكون فيها تمهيد قصير ثم قفشة واضحة في الآخر.
        - لا تشرح النكتة.
        - لا تكتب عنوان.
        - لا تستخدم إيموجي.
        - لا تستخدم فصحى.
        - لا تستخدم ألفاظ مسيئة أو عنصرية.
        - الجملة لا تحتوي على اي علامات ترقيم او شرطات مائلة.
        - لا تكتب حكمة أو نصيحة.
        يجب ان تكون النقطة قصيرة لا تزيد عن 80 حرف.
        النكتة كلها تكون في سطر واحد.
        - النكتة تكون من جملة أو جملتين فقط.
        - كل مرة اكتب نكتة مختلفة تمامًا حتى لو نفس الكلمة.
        اكتب النكتة كأنها بوست فيسبوك مصري مضحك أو إفيه بيتقال بين صحاب.

        رقم الطلب:
        $nonce

        ارجع النكتة فقط.
        """.trimIndent()
    }
}
