package com.hager.joke.service

import java.util.UUID

object JokePromptBuilder {
    fun build(word: String): String {
        val nonce = UUID.randomUUID()
        return """
          
            أنت كاتب كوميدي مصري محترف.

            اكتب نكتة مصرية قصيرة جدًا.

            يجب أن تحتوي النكتة بشكل طبيعي على الكلمة:
            "$word"

            الشروط:
            - استخدم العامية المصرية فقط.
            - استخدم الحروف العربية فقط.
            - ممنوع أي كلمات إنجليزية أو فرانكو.
            - اجعل النكتة مبنية على موقف مصري واقعي.
            - النهاية تكون مفاجئة ومضحكة.
            - لا تكرر الكلمة أكثر من مرة أو مرتين.
            - لا تشرح النكتة.
            - لا تضع عنوانًا أو إيموجي أو علامات اقتباس.
            - جملتان كحد أقصى.
            - أرجع النكتة فقط.

            رقم الطلب:
            $nonce
        """.trimIndent()
    }
}
